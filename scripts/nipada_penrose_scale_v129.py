DIMS = ["subtype", "signature", "slots", "frame", "edges", "iso", "formula"]


def evaluate(e: dict) -> dict:
    """Évalue les 7 dimensions de couverture d'un énoncé."""
    detected = _v122.dominant_subtype(e["text"])
    cov = {}
    cov["subtype"] = (detected == e["subtype"])
    cov["subtype_detected"] = detected
    atoms = e["atoms"]
    cov["signature"] = bool(atoms) and all(a in PRIMES for a in atoms)
    cov["signature_value"] = sig(*atoms) if atoms else None
    cov["slots"] = bool(e["slots"])
    cov["frame"] = bool(e["frame"])
    cov["edges"] = bool(e["edges"]) and all("type" in x for x in e["edges"])
    cov["iso"] = e["iso"] is not None
    cov["formula"] = e["formula_complexity"] >= 2  # 2-3 = formule riche encodable §128
    cov["formula_complexity"] = e["formula_complexity"]
    n_cov = sum(1 for d in DIMS if cov[d])
    cov["score"] = n_cov / len(DIMS)
    return cov


def main():
    detailed = []
    for e in CORPUS:
        c = evaluate(e)
        detailed.append({
            "id": e["id"],
            "chap": e["chap"],
            "subtype_expected": e["subtype"],
            "text_excerpt": e["text"][:90] + ("..." if len(e["text"]) > 90 else ""),
            "coverage": c,
        })

    n = len(detailed)
    means = {d: sum(1 for x in detailed if x["coverage"][d]) / n for d in DIMS}
    score_global = sum(x["coverage"]["score"] for x in detailed) / n

    by_chap = {}
    for ch in [5, 11, 13, 19, 24]:
        sub = [x for x in detailed if x["chap"] == ch]
        if sub:
            by_chap[f"chap_{ch}"] = {
                "n": len(sub),
                "score_moyen": sum(x["coverage"]["score"] for x in sub) / len(sub),
                "subtype_acc": sum(1 for x in sub if x["coverage"]["subtype"]) / len(sub),
            }

    by_sub = {}
    for st in _v122.MATH_SUBTYPES:
        sub = [x for x in detailed if x["subtype_expected"] == st]
        if sub:
            by_sub[st] = {
                "n": len(sub),
                "subtype_acc": sum(1 for x in sub if x["coverage"]["subtype"]) / len(sub),
                "score_moyen": sum(x["coverage"]["score"] for x in sub) / len(sub),
            }

    out = {
        "version": "v129",
        "context": "§129 — Validation Penrose à grande échelle (5 chapitres × 40 énoncés)",
        "n_enonces": n,
        "score_couverture_global": score_global,
        "moyennes_par_dimension": means,
        "par_chapitre": by_chap,
        "par_sous_type": by_sub,
        "detailed": detailed,
        "conclusion": {
            "couverture_universelle_4dim": (means["subtype"] + means["signature"] + means["slots"] + means["frame"]) / 4,
            "couverture_optionnelle_3dim": (means["edges"] + means["iso"] + means["formula"]) / 3,
            "verdict": "V8_math digère Penrose à {:.1%} sur 200 énoncés multi-chapitres.".format(score_global),
        }
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"§129 — Validation Penrose à grande échelle")
    print(f"  n énoncés : {n}")
    print(f"  Score couverture global : {score_global:.3f}")
    print(f"  Couverture par dimension :")
    for d, v in means.items():
        print(f"    {d:15s} {v:.3f}")
    print(f"  Par chapitre :")
    for k, v in by_chap.items():
        print(f"    {k}: score={v['score_moyen']:.3f}  subtype_acc={v['subtype_acc']:.3f}")
    print(f"  4 dim universelles (subtype/sig/slots/frame): {out['conclusion']['couverture_universelle_4dim']:.3f}")
    print(f"  3 dim optionnelles (edges/iso/formula)      : {out['conclusion']['couverture_optionnelle_3dim']:.3f}")
    print(f"→ {OUT}")


